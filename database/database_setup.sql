-- ---------------------------------------------------------------------------
-- physician_schedule_rules: recurring weekly working hours
-- ---------------------------------------------------------------------------
create table public.physician_schedule_rules (
  rule_id integer generated always as identity primary key,
  physician_user_id integer not null references public.users (user_id),
  weekday smallint not null,                 -- 0 = Sunday ... 6 = Saturday (Postgres dow)
  start_minute smallint not null,            -- local minutes after midnight
  end_minute smallint not null,
  slot_minutes smallint not null,            -- appointment duration
  timezone text not null,                    -- IANA name, e.g. America/New_York
  effective_from date not null default current_date,
  effective_to date,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint physician_schedule_rules_weekday_check check (weekday between 0 and 6),
  constraint physician_schedule_rules_window_check
    check (start_minute >= 0 and end_minute <= 1440 and end_minute > start_minute),
  constraint physician_schedule_rules_duration_check check (slot_minutes between 10 and 120),
  constraint physician_schedule_rules_fit_check
    check ((end_minute - start_minute) % slot_minutes = 0),
  constraint physician_schedule_rules_dates_check
    check (effective_to is null or effective_to >= effective_from),
  -- A physician cannot have two overlapping active windows on the same weekday.
  constraint physician_schedule_rules_no_overlap exclude using gist (
    physician_user_id with =,
    weekday with =,
    int4range(start_minute, end_minute) with &&,
    daterange(effective_from, effective_to, '[]') with &&
  ) where (is_active)
);
create index physician_schedule_rules_physician_idx
  on public.physician_schedule_rules (physician_user_id) where is_active;

-- ---------------------------------------------------------------------------
-- physician_schedule_exceptions: time off / blocked slots / one-off openings
