  reason text,                               -- internal; never shown to patients
  is_active boolean not null default true,
  created_at timestamptz not null default now(),

  constraint physician_schedule_exceptions_kind_check
    check (kind in ('unavailable', 'extra_availability')),
  constraint physician_schedule_exceptions_range_check
