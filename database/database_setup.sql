-- ---------------------------------------------------------------------------
-- 4. coordinate_correction_task: the ONLY way a Technician moves a correction task.
--    Actions (HOLD / DENY vocabulary; there is deliberately no ALLOW):
--      request_physician_authorization   HOLD -> physician approval   (alias: ready_for_review)
--      request_information               HOLD -> needs information
--      decline_<reason>                  DENY, administrative reasons only, only before any approval exists:
--                                        decline_duplicate_request | decline_incomplete_information |
--                                        decline_withdrawn_by_patient | decline_not_a_correction_request
--      close                             after the Physician has finally decided (re-validated)
-- ---------------------------------------------------------------------------
create or replace function public.coordinate_correction_task(
  p_task_id integer,
  p_actor_user_id integer,
  p_action text,
  p_internal_note text,
  p_patient_message text
)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
declare
  v_task public.technician_tasks;
  v_note text := nullif(btrim(p_internal_note), '');
  v_message text := nullif(btrim(p_patient_message), '');
  v_action text := case when p_action = 'ready_for_review' then 'request_physician_authorization' else p_action end;
  v_approval text;
  v_from text;
  v_to text;
  v_event text;
  v_final_message text;
  v_decision text;
  v_hold text;
  v_guardrail text;
  v_guardrail_reason text;
  v_outcome text := 'recorded';
  v_reason_code text;
  v_audit text;
  v_reviewer integer;
  v_candidate integer;
  v_reviewer_count integer := 0;
  v_existing_reviewer integer;
begin
  if v_action is null or not (
       v_action in ('request_physician_authorization', 'request_information', 'close',
                    'decline_duplicate_request', 'decline_incomplete_information',
                    'decline_withdrawn_by_patient', 'decline_not_a_correction_request')) then
    raise exception using errcode = 'PT422', message = 'Unknown coordination action.', detail = 'invalid_action';
  end if;
  if (v_note is not null and char_length(v_note) > 2000)
     or (v_message is not null and char_length(v_message) > 500) then
    raise exception using errcode = 'PT422', message = 'Text is too long.', detail = 'invalid_input';
  end if;

  v_task := hasf_private.lock_actor_task(p_task_id, p_actor_user_id);

  if v_task.category is distinct from 'record_correction' then
    raise exception using
      errcode = 'PT409', message = 'This is not a correction coordination task.', detail = 'not_a_correction_task';
  end if;
  if v_task.status in ('Completed', 'Declined', 'Cancelled') then
    raise exception using errcode = 'PT409', message = 'This task is closed.', detail = 'invalid_state';
  end if;

  v_approval := hasf_private.correction_approval_status(v_task);
  v_from := v_task.status;

  if v_action = 'request_physician_authorization' then
    if v_task.status <> 'In Review' then
      raise exception using errcode = 'PT409', message = 'Start the review first.', detail = 'invalid_state';
    end if;
    if v_approval not in ('not_requested', 'pending') then
      raise exception using
        errcode = 'PT409', message = 'The Physician review cannot be requested now.',
        detail = case when v_approval in ('approved', 'rejected') then 'already_decided' else 'approval_invalid' end;
    end if;
    if v_note is null then
      raise exception using errcode = 'PT422', message = 'An internal note is required.', detail = 'note_required';
    end if;

    perform 1 from public.patient_assignments as assignment where assignment.patient_id = v_task.patient_id for update;
    perform 1 from public.users as reviewer
      where reviewer.user_id in (select a.staff_user_id from public.patient_assignments as a where a.patient_id = v_task.patient_id)
      for share;
    perform 1 from public.permissions as permission
      where permission.role = 'Physician' and permission.action = 'review_escalation' for share;

    for v_candidate in
      select distinct reviewer.user_id
      from public.patient_assignments as assignment
      join public.users as reviewer on reviewer.user_id = assignment.staff_user_id
      join public.permissions as permission
        on permission.role = 'Physician' and permission.action = 'review_escalation' and permission.allowed is true
      where assignment.patient_id = v_task.patient_id and reviewer.role = 'Physician' and reviewer.is_active is true
    loop
      v_reviewer_count := v_reviewer_count + 1;
      v_reviewer := v_candidate;
    end loop;
    if v_reviewer_count <> 1 then
      raise exception using
        errcode = 'PT409', message = 'No unique active assigned Physician is authorized to review this request.',
        detail = 'no_unique_reviewer';
    end if;
    if not hasf_private.physician_can_process_approvals(v_reviewer) then
      raise exception using
        errcode = 'PT409', message = 'The assigned Physician cannot process approvals yet.', detail = 'physician_unreachable';
    end if;

    if v_approval = 'pending' then
      -- Reuse the one valid approval; never create a second.
      select a.reviewer_id into v_existing_reviewer from public.approvals as a where a.request_id = v_task.approval_request_id;
      if v_existing_reviewer is null or not hasf_private.physician_can_process_approvals(v_existing_reviewer) then
        raise exception using
          errcode = 'PT409', message = 'The Physician on the existing approval cannot process it.', detail = 'physician_unreachable';
      end if;
      v_outcome := 'approval_reused';
    else
      perform pg_catalog.set_config('hasf.correction_coordination', 'on', true);
      perform pg_catalog.set_config('hasf.correction_actor', p_actor_user_id::text, true);
      insert into public.approvals (request_id, reviewer_id, status)
      values (v_task.approval_request_id, v_reviewer, 'Pending');
      v_outcome := 'approval_requested';
    end if;

    v_to := 'Awaiting Physician';
    v_event := 'decision';
    v_decision := 'HOLD';
    v_hold := 'physician_approval';
    v_guardrail := 'Escalate';
    v_guardrail_reason := 'clinical_requires_physician';
    v_final_message := coalesce(v_message, 'With your Physician for review.');
    v_audit := 'request_physician_authorization';

  elsif v_action = 'request_information' then
    if v_task.status not in ('In Review', 'Awaiting Physician') then
      raise exception using errcode = 'PT409', message = 'That action is not available now.', detail = 'invalid_state';
    end if;
    if v_approval not in ('not_requested', 'pending') then
      raise exception using
        errcode = 'PT409', message = 'The Physician review is not open.',
        detail = case when v_approval in ('approved', 'rejected') then 'already_decided' else 'approval_invalid' end;
    end if;
    if v_note is null then
      raise exception using errcode = 'PT422', message = 'An internal note is required.', detail = 'note_required';
    end if;
    if v_message is null or char_length(v_message) < 10 then
      raise exception using
        errcode = 'PT422', message = 'Ask the Patient a specific question.', detail = 'information_request_too_short';
    end if;
    v_to := 'On Hold';
    v_event := 'coordination_info_requested';
    v_decision := 'HOLD';
    v_final_message := v_message;
    v_audit := 'request_information';

  elsif v_action = 'close' then
    if v_approval not in ('approved', 'rejected') then
      raise exception using
        errcode = 'PT409', message = 'The Physician has not finally decided this correction.',
        detail = case when v_approval in ('pending', 'not_requested') then 'approval_pending' else 'approval_invalid' end;
    end if;
    v_to := 'Completed';
    v_event := 'coordination_closed';
    v_final_message := coalesce(v_message, 'Your Physician has reviewed this correction. The outcome is shown with your request.');
    v_audit := 'close';

  else
    -- DENY: administrative reasons only, and only while no Physician approval exists.
    v_reason_code := substr(v_action, char_length('decline_') + 1);
    if v_approval <> 'not_requested' then
      raise exception using
        errcode = 'PT409', message = 'A correction cannot be declined once the Physician review exists.',
        detail = case v_approval when 'pending' then 'cannot_decline_after_authorization'
                                 when 'invalid' then 'approval_invalid' else 'already_decided' end;
    end if;
    if v_task.status not in ('In Review', 'On Hold') then
      raise exception using errcode = 'PT409', message = 'Start the review first.', detail = 'invalid_state';
    end if;
    if v_note is null then
      raise exception using errcode = 'PT422', message = 'An internal note is required.', detail = 'note_required';
    end if;
    if v_message is null or char_length(v_message) < 20 then
      raise exception using
        errcode = 'PT422', message = 'Explain the reason to the Patient.', detail = 'rejection_reason_too_short';
    end if;
    if v_reason_code = 'incomplete_information' and not exists (
         select 1 from public.technician_task_events as e
         where e.task_id = v_task.task_id and e.event_type = 'coordination_info_requested') then
      raise exception using
        errcode = 'PT409', message = 'Ask the Patient for the missing information first.', detail = 'follow_up_required';
    end if;
    v_to := 'Declined';
    v_event := 'decision';
    v_decision := 'BLOCK';
    v_guardrail := 'Allow';
    v_guardrail_reason := 'admin_' || v_reason_code;
    v_final_message := v_message;
    v_audit := 'decline';
  end if;

  perform pg_catalog.set_config('hasf.correction_coordination', 'on', true);
  update public.technician_tasks
     set status = v_to,
         latest_decision = coalesce(v_decision, latest_decision),
         patient_message = v_final_message,
         closed_at = case when v_to in ('Completed', 'Declined') then pg_catalog.now() else closed_at end
   where task_id = v_task.task_id;
  perform pg_catalog.set_config('hasf.correction_coordination', '', true);
  perform pg_catalog.set_config('hasf.correction_actor', '', true);

  insert into public.technician_task_events (
    task_id, actor_user_id, actor_role, event_type, decision, hold_reason, from_status, to_status,
    guardrail_decision, guardrail_reason, internal_note, patient_message, approval_request_id
  ) values (
    v_task.task_id, p_actor_user_id, 'Technician', v_event,
    case when v_event = 'decision' then v_decision else null end,
    case when v_event = 'decision' and v_decision = 'HOLD' then v_hold else null end,
    v_from, v_to,
    case when v_event = 'decision' then v_guardrail else null end,
    case when v_event = 'decision' then v_guardrail_reason else null end,
    v_note, v_final_message, v_task.approval_request_id
  );

  insert into public.audit_logs (request_id, user_id, event_type, details)
  values (
    v_task.approval_request_id, p_actor_user_id, 'technician.correction.' || v_audit,
    pg_catalog.jsonb_build_object('task_id', v_task.task_id, 'request_id', v_task.approval_request_id,
                                  'outcome', v_outcome, 'reason_code', v_reason_code)::text
  );

  return pg_catalog.jsonb_build_object('task_id', v_task.task_id, 'status', v_to, 'action', p_action,
                                       'outcome', v_outcome);
end;
$function$;

