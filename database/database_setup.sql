    v_task.approval_request_id,
    p_actor_user_id,
    'technician.task.completed',
    jsonb_build_object('task_id', v_task.task_id, 'from', 'In Progress', 'to', 'Completed')::text
  );

  return jsonb_build_object('task_id', v_task.task_id, 'status', 'Completed');
