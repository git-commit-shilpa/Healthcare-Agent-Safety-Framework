create function hasf_private.schedule_rules_guard()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
begin
  if not exists (select 1 from pg_catalog.pg_timezone_names as z where z.name = new.timezone) then
    raise exception using errcode = 'PT422', message = 'Unknown time zone.', detail = 'invalid_timezone';
  end if;
  if not exists (
    select 1 from public.users as u
    where u.user_id = new.physician_user_id and u.role = 'Physician'
  ) then
    raise exception using errcode = 'PT422', message = 'The schedule owner must be a Physician.', detail = 'not_physician';
  end if;
  -- One time zone per physician keeps display unambiguous.
  if new.is_active and exists (
    select 1 from public.physician_schedule_rules as r
    where r.physician_user_id = new.physician_user_id
      and r.is_active and r.rule_id is distinct from new.rule_id
      and r.timezone <> new.timezone
  ) then
    raise exception using errcode = 'PT422', message = 'All schedule rules of a physician must share one time zone.', detail = 'timezone_mismatch';
  end if;
  if tg_op = 'UPDATE' then
    if new.physician_user_id is distinct from old.physician_user_id then
      raise exception using errcode = 'PT409', message = 'The schedule owner cannot change.', detail = 'immutable_fields';
    end if;
    new.updated_at := pg_catalog.now();
  end if;
  return new;
end;
$function$;

