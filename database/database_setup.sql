-- ---------------------------------------------------------------------------
-- 3. Guard: only the coordination RPC may move a correction task through its states.
--    INSERT : the task must point at a real correction of the SAME patient and requester.
--    UPDATE : the approval link is immutable; status / latest_decision changes need the
--             transaction-local flag set by coordinate_correction_task(), except the harmless
--             "start / resume review" (Submitted|On Hold -> In Review), which also covers the Patient
--             answering a question. Every other path (ALLOW, BLOCK, HOLD->physician_approval,
--             complete, Patient cancel) fails with PT409 correction_coordination_only.
-- ---------------------------------------------------------------------------
create function hasf_private.correction_task_guard()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
begin
  if tg_op = 'INSERT' then
    if new.category = 'record_correction' then
      if new.approval_request_id is null
         or new.requires_physician_approval is not true
         or not exists (
           select 1 from public.ai_requests as r
           where r.request_id = new.approval_request_id
             and r.action = 'patient_treatment_correction'
             and r.patient_id = new.patient_id
             and r.requested_by = new.requested_by
         ) then
        raise exception using
          errcode = 'PT422', message = 'A correction task must link an existing correction request.',
          detail = 'invalid_correction_link';
      end if;
    end if;
    return new;
  end if;

  if old.category is distinct from 'record_correction' then
    return new;
  end if;

  if new.approval_request_id is distinct from old.approval_request_id then
    raise exception using
      errcode = 'PT409', message = 'The correction link cannot be changed.',
      detail = 'immutable_fields';
  end if;

  if (new.status is distinct from old.status or new.latest_decision is distinct from old.latest_decision)
     and pg_catalog.current_setting('hasf.correction_coordination', true) is distinct from 'on'
     and not (
       old.status in ('Submitted', 'On Hold')
       and new.status = 'In Review'
       and new.latest_decision is not distinct from old.latest_decision
     ) then
    raise exception using
      errcode = 'PT409',
      message = 'Correction requests can only be coordinated, not decided, by a Technician.',
      detail = 'correction_coordination_only';
  end if;

  return new;
end;
$function$;

