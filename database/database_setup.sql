-- ---------------------------------------------------------------------------
-- submit_appointment_request: validates the slot, then reuses submit_service_request
-- (patient lock, open-request cap, duplicate check, advisory-locked Technician
-- assignment, audit) and records the appointment, all in one transaction.
-- Does NOT reserve the slot.
-- ---------------------------------------------------------------------------
create function public.submit_appointment_request(
  p_requested_by integer,
  p_physician_id integer,
  p_starts_at timestamptz,
  p_reason text,
  p_guardrail_reason text
)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
declare
  v_reason text := nullif(btrim(p_reason), '');
  v_end timestamptz;
  v_zone text;
  v_name text;
  v_title text;
  v_result jsonb;
  v_task_id integer;
  v_patient_id integer;
  v_appointment_id integer;
begin
  if p_requested_by is null or p_requested_by <= 0
     or p_physician_id is null or p_physician_id <= 0
     or p_starts_at is null
     or (v_reason is not null and char_length(v_reason) > 500) then
    raise exception using errcode = 'PT422', message = 'Invalid appointment request.', detail = 'invalid_input';
  end if;
  if p_starts_at <= pg_catalog.now() + interval '120 minutes'
     or p_starts_at > pg_catalog.now() + interval '61 days' then
    raise exception using errcode = 'PT422', message = 'The requested time is outside the bookable window.', detail = 'invalid_date';
  end if;

  perform 1 from public.permissions as permission
  where permission.role = 'Patient' and permission.action = 'request_appointment' for share;
  if not exists (
    select 1 from public.permissions as permission
    where permission.role = 'Patient' and permission.action = 'request_appointment'
      and permission.allowed is true
  ) then
    raise exception using errcode = 'PT403', message = 'The Patient account may not request appointments.', detail = 'permission_missing';
  end if;

  -- Stale-availability guard: the slot must exist in the CURRENT schedule and be unreserved.
  select s.slot_end, s.slot_timezone into v_end, v_zone
  from hasf_private.generate_slots(
    p_physician_id,
    ((p_starts_at at time zone 'UTC')::date - 1),
    ((p_starts_at at time zone 'UTC')::date + 1),
    pg_catalog.now() + interval '120 minutes',
    null
  ) as s
  where s.slot_start = p_starts_at;

  if v_end is null then
    raise exception using errcode = 'PT409', message = 'That time is no longer available.', detail = 'slot_unavailable';
  end if;

  select u.name into v_name from public.users as u where u.user_id = p_physician_id;
  v_title := left(
    'Appointment with ' || coalesce(v_name, 'doctor') || ' on '
    || pg_catalog.to_char(p_starts_at at time zone v_zone, 'YYYY-MM-DD HH24:MI') || ' ' || v_zone,
    200
  );

  v_result := public.submit_service_request(
    p_requested_by, 'appointment_scheduling', v_title, v_reason, p_guardrail_reason
  );
  v_task_id := (v_result ->> 'task_id')::integer;

  select t.patient_id into v_patient_id from public.technician_tasks as t where t.task_id = v_task_id;

  -- A patient cannot hold two live overlapping requests, even with different doctors.
  if exists (
    select 1 from public.appointments as a
    where a.patient_id = v_patient_id
      and a.status in ('Pending Confirmation', 'Needs Information', 'Awaiting Physician', 'Confirmed')
      and pg_catalog.tstzrange(a.starts_at, a.ends_at) && pg_catalog.tstzrange(p_starts_at, v_end)
  ) then
    raise exception using errcode = 'PT409', message = 'You already have an appointment request at that time.', detail = 'patient_overlap';
  end if;

  insert into public.appointments (
    task_id, patient_id, physician_user_id, starts_at, ends_at, physician_timezone, reason
  ) values (
    v_task_id, v_patient_id, p_physician_id, p_starts_at, v_end, v_zone, v_reason
  )
  returning appointment_id into v_appointment_id;

  insert into public.audit_logs (user_id, event_type, details)
  values (
    p_requested_by, 'patient.appointment.requested',
    pg_catalog.jsonb_build_object(
      'task_id', v_task_id, 'appointment_id', v_appointment_id, 'physician_user_id', p_physician_id
    )::text
  );

  return pg_catalog.jsonb_build_object(
    'task_id', v_task_id,
    'appointment_id', v_appointment_id,
    'status', 'Pending Confirmation',
    'task_status', 'Submitted',
    'starts_at', p_starts_at,
    'ends_at', v_end,
    'timezone', v_zone
  );
end;
$function$;

-- ---------------------------------------------------------------------------
-- Status synchronisation. Runs inside the transaction of the existing task RPCs.
-- ---------------------------------------------------------------------------
create function hasf_private.appointment_sync_task_status()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
declare
  v_apt public.appointments;
  v_target text;
  v_event record;
  v_len integer;
begin
  if new.status is not distinct from old.status then
    return new;
  end if;

  select * into v_apt from public.appointments as a where a.task_id = new.task_id for update;
  if not found then
    return new;                      -- an ordinary service request
  end if;

  v_target := case new.status
    when 'In Review' then 'Pending Confirmation'
    when 'On Hold' then 'Needs Information'
    when 'Awaiting Physician' then 'Awaiting Physician'
    when 'In Progress' then 'Confirmed'
    when 'Declined' then 'Rejected'
    when 'Cancelled' then 'Cancelled'
    when 'Completed' then 'Completed'
    else null
  end;
  if v_target is null or v_target = v_apt.status then
    return new;
  end if;

  -- The decision RPC writes its event before updating the task, so the latest event
  -- is the decision that caused this transition.
  select e.actor_user_id, e.event_type, e.decision, e.hold_reason, e.patient_message
  into v_event
  from public.technician_task_events as e
  where e.task_id = new.task_id
  order by e.event_id desc
  limit 1;

  v_len := coalesce(char_length(btrim(v_event.patient_message)), 0);

  if v_target = 'Confirmed' then
    if v_event.event_type is distinct from 'decision' or v_event.decision is distinct from 'ALLOW' or v_len < 10 then
      raise exception using
        errcode = 'PT422', message = 'A confirmation message for the patient is required.',
        detail = 'confirmation_message_required';
    end if;
    -- Final availability re-check (lead time does not apply to an existing request).
    if not hasf_private.slot_is_bookable(
         v_apt.physician_user_id, v_apt.starts_at, v_apt.ends_at, pg_catalog.now(), v_apt.appointment_id
       ) then
      raise exception using errcode = 'PT409', message = 'The doctor is no longer available at that time.', detail = 'slot_unavailable';
    end if;
    begin
      update public.appointments
      set status = 'Confirmed', confirmed_by = v_event.actor_user_id, confirmed_at = pg_catalog.now()
      where appointment_id = v_apt.appointment_id;
    exception when exclusion_violation then
      raise exception using errcode = 'PT409', message = 'That time has just been booked.', detail = 'slot_unavailable';
    end;
    insert into public.audit_logs (user_id, event_type, details)
    values (
      v_event.actor_user_id, 'technician.appointment.confirmed',
      pg_catalog.jsonb_build_object('task_id', new.task_id, 'appointment_id', v_apt.appointment_id)::text
    );
    return new;
  end if;

  if v_target = 'Rejected' and (v_event.decision is distinct from 'BLOCK' or v_len < 20) then
    raise exception using
      errcode = 'PT422', message = 'Please explain the rejection to the patient (at least 20 characters).',
      detail = 'rejection_reason_too_short';
  end if;
  if v_target = 'Needs Information' and (v_event.hold_reason is distinct from 'needs_information' or v_len < 10) then
    raise exception using
      errcode = 'PT422', message = 'Please tell the patient what information is needed (at least 10 characters).',
      detail = 'information_request_too_short';
  end if;

  update public.appointments set status = v_target where appointment_id = v_apt.appointment_id;

  -- Supplementary row; the underlying task RPC already audited the real actor.
  insert into public.audit_logs (user_id, event_type, details)
  values (
    case v_target
      when 'Rejected' then v_event.actor_user_id
      when 'Needs Information' then v_event.actor_user_id
      when 'Awaiting Physician' then v_event.actor_user_id
      when 'Completed' then new.assigned_to
      else new.requested_by
    end,
    'appointment.status.' || pg_catalog.lower(pg_catalog.replace(v_target, ' ', '_')),
    pg_catalog.jsonb_build_object('task_id', new.task_id, 'appointment_id', v_apt.appointment_id)::text
  );
  return new;
end;
$function$;

create trigger technician_tasks_appointment_sync
  after update of status on public.technician_tasks
  for each row execute function hasf_private.appointment_sync_task_status();

-- ---------------------------------------------------------------------------
-- check_appointment_slot: READ-ONLY pre-flight for the Technician's "Confirm Appointment"
-- button. It reserves nothing; the real check + reservation happen again, atomically, when
-- the decision is recorded. Answers: ok | already_confirmed | slot_unavailable |
-- physician_unavailable | not_pending.
-- ---------------------------------------------------------------------------
create function public.check_appointment_slot(
  p_task_id integer,
  p_actor_user_id integer
)
returns jsonb
language plpgsql
stable
security invoker
set search_path = pg_catalog
as $function$
declare
  v_apt public.appointments;
  v_status text;
begin
  if p_task_id is null or p_task_id <= 0 or p_actor_user_id is null or p_actor_user_id <= 0 then
    raise exception using errcode = 'PT422', message = 'Invalid task or actor.', detail = 'invalid_input';
  end if;

  select a.* into v_apt
  from public.appointments as a
  join public.technician_tasks as t on t.task_id = a.task_id
  where a.task_id = p_task_id
    and t.assigned_to = p_actor_user_id
    and exists (
      select 1 from public.users as u
      where u.user_id = p_actor_user_id and u.role = 'Technician' and u.is_active is true
    )
    and exists (
      select 1 from public.patient_assignments as pa
      where pa.patient_id = t.patient_id and pa.staff_user_id = p_actor_user_id
    );

  if not found then
    raise exception using errcode = 'PT404', message = 'Task not found.', detail = 'not_found';
  end if;

  if v_apt.status in ('Confirmed', 'Completed') then
    v_status := 'already_confirmed';
  elsif v_apt.status not in ('Pending Confirmation', 'Awaiting Physician') then
    v_status := 'not_pending';
  elsif not hasf_private.physician_is_bookable(v_apt.physician_user_id) then
    v_status := 'physician_unavailable';
  elsif hasf_private.slot_is_bookable(
          v_apt.physician_user_id, v_apt.starts_at, v_apt.ends_at, pg_catalog.now(), v_apt.appointment_id) then
    v_status := 'ok';
  else
    v_status := 'slot_unavailable';
  end if;

  return pg_catalog.jsonb_build_object(
    'task_id', p_task_id, 'result', v_status, 'bookable', v_status = 'ok');
end;
$function$;

-- ---------------------------------------------------------------------------
-- Physician schedule management (called by FastAPI with a VERIFIED physician id).
-- ---------------------------------------------------------------------------
create function hasf_private.assert_schedule_actor(p_actor_user_id integer)
returns void
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
begin
  if p_actor_user_id is null or p_actor_user_id <= 0 then
    raise exception using errcode = 'PT422', message = 'Invalid actor.', detail = 'invalid_input';
  end if;
  perform 1 from public.users as u where u.user_id = p_actor_user_id for share;
  perform 1 from public.permissions as p
  where p.role = 'Physician' and p.action = 'manage_own_schedule' for share;
  if not exists (
    select 1 from public.users as u
    where u.user_id = p_actor_user_id and u.role = 'Physician' and u.is_active is true
  ) then
    raise exception using errcode = 'PT403', message = 'The actor is not an active Physician.', detail = 'not_physician';
  end if;
  if not exists (
    select 1 from public.permissions as p
    where p.role = 'Physician' and p.action = 'manage_own_schedule' and p.allowed is true
  ) then
    raise exception using errcode = 'PT403', message = 'Schedule management is not enabled for Physicians.', detail = 'permission_missing';
  end if;
end;
$function$;

create function public.upsert_schedule_rule(
  p_actor_user_id integer,
  p_rule_id integer,
  p_weekday integer,
  p_start_minute integer,
  p_end_minute integer,
  p_slot_minutes integer,
  p_timezone text,
  p_effective_from date,
  p_effective_to date
)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
declare
  v_rule_id integer;
begin
  perform hasf_private.assert_schedule_actor(p_actor_user_id);
  if p_timezone is null or p_weekday is null or p_start_minute is null
     or p_end_minute is null or p_slot_minutes is null then
    raise exception using errcode = 'PT422', message = 'Invalid schedule rule.', detail = 'invalid_input';
  end if;

  begin
    if p_rule_id is null then
      insert into public.physician_schedule_rules (
        physician_user_id, weekday, start_minute, end_minute, slot_minutes, timezone,
        effective_from, effective_to
      ) values (
        p_actor_user_id, p_weekday, p_start_minute, p_end_minute, p_slot_minutes, p_timezone,
        coalesce(p_effective_from, current_date), p_effective_to
      ) returning rule_id into v_rule_id;
    else
      update public.physician_schedule_rules
      set weekday = p_weekday, start_minute = p_start_minute, end_minute = p_end_minute,
          slot_minutes = p_slot_minutes, timezone = p_timezone,
          effective_from = coalesce(p_effective_from, effective_from), effective_to = p_effective_to,
          is_active = true
      where rule_id = p_rule_id and physician_user_id = p_actor_user_id
      returning rule_id into v_rule_id;
      if v_rule_id is null then
        raise exception using errcode = 'PT404', message = 'Schedule rule not found.', detail = 'not_found';
      end if;
    end if;
