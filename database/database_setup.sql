  values (p_actor_user_id, 'physician.schedule.rule_saved',
          pg_catalog.jsonb_build_object('rule_id', v_rule_id)::text);
  return pg_catalog.jsonb_build_object('rule_id', v_rule_id);
end;
$function$;

