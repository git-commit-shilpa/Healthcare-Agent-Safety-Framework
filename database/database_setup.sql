  );

  return jsonb_build_object(
    'task_id', v_task.task_id,
    'status', v_to,
    'latest_decision', p_decision,
    'outcome', v_outcome,
    'approval_request_id', v_request_id,
    'approval_status', case when v_request_id is null then null else 'Pending' end
  );
end;
