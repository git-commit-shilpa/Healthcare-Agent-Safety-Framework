-- ---------------------------------------------------------------------------
-- 4a. Internal helper: approval state for a task, re-validated on every call.
--     Returns: none | pending | approved | rejected | invalid
--     'approved' requires: exactly one approvals row, tied to THIS patient, THIS
--     task and the technician_task_approval action, reviewed (reviewed_at set) by
--     a still-active Physician who is still assigned to the patient, still holds
--     review_escalation, and is not the task's Technician.
-- ---------------------------------------------------------------------------
create function hasf_private.task_approval_status(p_task public.technician_tasks)
returns text
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
declare
  v_count integer;
  v_status text;
  v_reviewer integer;
  v_reviewed_at timestamptz;
  v_patient integer;
  v_action text;
  v_details_text text;
  v_details jsonb;
begin
  if p_task.approval_request_id is null then
    return 'none';
  end if;

  -- Stabilize the approval rows for the caller's transaction.
  perform 1
  from public.approvals as a
  where a.request_id = p_task.approval_request_id
  for share;

  select count(*) into v_count
  from public.approvals as a
  where a.request_id = p_task.approval_request_id;

  if v_count <> 1 then
    return 'invalid';
  end if;

  select a.status, a.reviewer_id, a.reviewed_at
  into v_status, v_reviewer, v_reviewed_at
  from public.approvals as a
  where a.request_id = p_task.approval_request_id;

  select r.patient_id, r.action, r.request_details
  into v_patient, v_action, v_details_text
  from public.ai_requests as r
  where r.request_id = p_task.approval_request_id;

  if v_patient is distinct from p_task.patient_id
     or v_action is distinct from 'technician_task_approval' then
    return 'invalid';
  end if;

  begin
    v_details := v_details_text::jsonb;
  exception when others then
    return 'invalid';
  end;

  if (v_details ->> 'task_id') is distinct from p_task.task_id::text then
    return 'invalid';
  end if;

  if v_status = 'Pending' then
    return 'pending';
  elsif v_status = 'Rejected' then
    return 'rejected';
  elsif v_status = 'Approved' then
    if v_reviewed_at is null
       or v_reviewer is null
       or v_reviewer = p_task.assigned_to then
      return 'invalid';
    end if;

    if not exists (
      select 1
      from public.users as reviewer
      join public.patient_assignments as assignment
        on assignment.staff_user_id = reviewer.user_id
       and assignment.patient_id = p_task.patient_id
      join public.permissions as permission
        on permission.role = 'Physician'
       and permission.action = 'review_escalation'
       and permission.allowed is true
      where reviewer.user_id = v_reviewer
        and reviewer.role = 'Physician'
        and reviewer.is_active is true
    ) then
      return 'invalid';
    end if;
    return 'approved';
  end if;

  return 'invalid';
end;
$function$;

-- ---------------------------------------------------------------------------
-- 4b. Internal helper: validate the acting Technician and lock the task.
--     "Not found" and "not assigned to you" are indistinguishable (PT404).
-- ---------------------------------------------------------------------------
create function hasf_private.lock_actor_task(
  p_task_id integer,
  p_actor_user_id integer
)
returns public.technician_tasks
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
declare
  v_task public.technician_tasks;
  v_permission_count integer;
begin
  if p_task_id is null or p_task_id <= 0
     or p_actor_user_id is null or p_actor_user_id <= 0 then
    raise exception using
      errcode = 'PT422', message = 'Invalid task or actor.', detail = 'invalid_input';
  end if;

  perform 1 from public.users as actor where actor.user_id = p_actor_user_id for share;

  if not exists (
    select 1 from public.users as actor
    where actor.user_id = p_actor_user_id
      and actor.role = 'Technician'
      and actor.is_active is true
  ) then
    raise exception using
      errcode = 'PT403', message = 'The actor is not an active Technician account.',
      detail = 'not_technician';
  end if;

  perform 1 from public.permissions as permission
  where permission.role = 'Technician'
    and permission.action in ('view_assigned_task', 'update_task_status')
  for share;

  select count(*) into v_permission_count
  from public.permissions as permission
  where permission.role = 'Technician'
    and permission.action in ('view_assigned_task', 'update_task_status')
    and permission.allowed is true;

  if v_permission_count <> 2 then
    raise exception using
      errcode = 'PT403', message = 'The Technician role may not update tasks.',
      detail = 'permission_missing';
  end if;

  select * into v_task
  from public.technician_tasks as task
  where task.task_id = p_task_id
    and task.assigned_to = p_actor_user_id
  for update;

  if not found then
    raise exception using
      errcode = 'PT404', message = 'Task not found.', detail = 'not_found';
  end if;

  -- The Technician must still be assigned to the patient.
  perform 1 from public.patient_assignments as assignment
  where assignment.patient_id = v_task.patient_id
    and assignment.staff_user_id = p_actor_user_id
  for share;

  if not found then
    raise exception using
      errcode = 'PT404', message = 'Task not found.', detail = 'not_found';
  end if;

  return v_task;
end;
$function$;

-- ---------------------------------------------------------------------------
-- 4c. start_technician_task_review: Submitted -> In Review, On Hold -> In Review
-- ---------------------------------------------------------------------------
create function public.start_technician_task_review(
  p_task_id integer,
  p_actor_user_id integer
)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
declare
  v_task public.technician_tasks;
  v_event_type text;
begin
  v_task := hasf_private.lock_actor_task(p_task_id, p_actor_user_id);

  if v_task.status = 'Submitted' then
    v_event_type := 'review_started';
  elsif v_task.status = 'On Hold' then
    v_event_type := 'review_resumed';
  else
    raise exception using
      errcode = 'PT409', message = 'The task cannot be moved to review from its current status.',
      detail = 'invalid_state';
  end if;

  update public.technician_tasks
  set status = 'In Review'
  where task_id = v_task.task_id;

  insert into public.technician_task_events (
    task_id, actor_user_id, actor_role, event_type, from_status, to_status
  ) values (
    v_task.task_id, p_actor_user_id, 'Technician', v_event_type, v_task.status, 'In Review'
  );

  insert into public.audit_logs (user_id, event_type, details)
  values (
    p_actor_user_id,
    'technician.task.' || v_event_type,
    jsonb_build_object('task_id', v_task.task_id, 'from', v_task.status, 'to', 'In Review')::text
  );

  return jsonb_build_object('task_id', v_task.task_id, 'status', 'In Review');
end;
$function$;

-- ---------------------------------------------------------------------------
-- 4d. record_technician_task_decision
--
--   p_guardrail_decision / p_guardrail_reason are the BACKEND's verdict on the
--   requested action (Allow | Block | Escalate). The RPC does not trust it
--   blindly: it independently re-verifies state, assignment, permission and the
--   approval link before executing anything.
--
--   ALLOW   + Allow    -> In Progress (needs a valid Approved approval if the task requires one)
--   ALLOW   + Block|Escalate -> nothing executes; a decision_rejected event is stored
--   BLOCK   + Allow    -> Declined (internal note and patient message mandatory)
--   HOLD needs_information  + Allow    -> On Hold (no physician approval is created)
--   HOLD physician_approval + Escalate -> Awaiting Physician; creates (or reuses the
--                         single pending) ai_requests + approvals row
-- ---------------------------------------------------------------------------
create function public.record_technician_task_decision(
  p_task_id integer,
  p_actor_user_id integer,
  p_decision text,
  p_hold_reason text,
  p_internal_note text,
  p_patient_message text,
  p_guardrail_decision text,
  p_guardrail_reason text
)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
declare
  v_task public.technician_tasks;
  v_approval text;
  v_note text := nullif(btrim(p_internal_note), '');
  v_message text := nullif(btrim(p_patient_message), '');
  v_reason text := nullif(btrim(p_guardrail_reason), '');
  v_from text;
  v_to text;
  v_outcome text;
  v_request_id integer;
  v_new_request_id integer;
  v_reviewer_id integer;
  v_candidate_reviewer_id integer;
  v_reviewer_count integer := 0;
begin
  if p_decision is null or p_decision not in ('ALLOW', 'BLOCK', 'HOLD') then
    raise exception using errcode = 'PT422', message = 'Invalid decision.', detail = 'invalid_decision';
  end if;
  if p_guardrail_decision is null or p_guardrail_decision not in ('Allow', 'Block', 'Escalate') then
    raise exception using errcode = 'PT422', message = 'Invalid guardrail decision.', detail = 'invalid_guardrail';
  end if;
  if v_reason is not null and char_length(v_reason) > 100 then
    raise exception using errcode = 'PT422', message = 'Guardrail reason is too long.', detail = 'invalid_guardrail';
  end if;
  if p_decision = 'HOLD' then
    if p_hold_reason is null or p_hold_reason not in ('needs_information', 'physician_approval') then
      raise exception using errcode = 'PT422', message = 'A hold reason is required.', detail = 'hold_reason_required';
    end if;
  elsif p_hold_reason is not null then
    raise exception using errcode = 'PT422', message = 'A hold reason applies only to HOLD.', detail = 'invalid_hold_reason';
  end if;
  if (p_internal_note is not null and char_length(p_internal_note) > 2000)
     or (p_patient_message is not null and char_length(p_patient_message) > 500) then
    raise exception using errcode = 'PT422', message = 'A note or message is too long.', detail = 'text_too_long';
  end if;
  if p_decision in ('BLOCK', 'HOLD') and (v_note is null or v_message is null) then
    raise exception using
      errcode = 'PT422',
      message = 'BLOCK and HOLD require an internal reason and a patient-facing message.',
      detail = 'note_required';
  end if;
  -- The guardrail verdict must match the kind of action being executed.
  if (p_decision = 'BLOCK' or (p_decision = 'HOLD' and p_hold_reason = 'needs_information'))
     and p_guardrail_decision <> 'Allow' then
    raise exception using errcode = 'PT422', message = 'The guardrail did not authorize this action.', detail = 'guardrail_mismatch';
  end if;
  if p_decision = 'HOLD' and p_hold_reason = 'physician_approval'
     and p_guardrail_decision <> 'Escalate' then
    raise exception using errcode = 'PT422', message = 'A physician hold must be an escalation.', detail = 'guardrail_mismatch';
  end if;

  v_task := hasf_private.lock_actor_task(p_task_id, p_actor_user_id);
  v_from := v_task.status;
  v_approval := hasf_private.task_approval_status(v_task);

  if (p_decision = 'ALLOW' and v_from not in ('In Review', 'Awaiting Physician'))
     or (p_decision = 'BLOCK' and v_from not in ('In Review', 'On Hold', 'Awaiting Physician'))
     or (p_decision = 'HOLD' and v_from <> 'In Review') then
    raise exception using
      errcode = 'PT409', message = 'This decision is not allowed from the task''s current status.',
      detail = 'invalid_state';
  end if;

  if p_decision = 'ALLOW' then
    if p_guardrail_decision <> 'Allow' then
      -- Nothing executes. Keep a record that the Technician's choice was overridden.
      insert into public.technician_task_events (
        task_id, actor_user_id, actor_role, event_type, decision, from_status, to_status,
        guardrail_decision, guardrail_reason, internal_note
      ) values (
        v_task.task_id, p_actor_user_id, 'Technician', 'decision_rejected', 'ALLOW', v_from, v_from,
        p_guardrail_decision, v_reason, v_note
      );
      insert into public.audit_logs (user_id, event_type, details)
      values (
        p_actor_user_id,
        'technician.task.decision_overridden_by_guardrail',
        jsonb_build_object(
          'task_id', v_task.task_id, 'decision', 'ALLOW',
          'guardrail_decision', p_guardrail_decision, 'reason', v_reason
        )::text
      );
      return jsonb_build_object(
        'task_id', v_task.task_id,
        'status', v_from,
        'latest_decision', v_task.latest_decision,
        'outcome', case p_guardrail_decision when 'Block' then 'rejected' else 'escalated' end
      );
    end if;

    -- Independent re-verification: the backend said Allow, but a clinical
    -- approval can never be bypassed by a Technician.
    if (v_task.requires_physician_approval or v_from = 'Awaiting Physician')
       and v_approval <> 'approved' then
      raise exception using
        errcode = 'PT409',
        message = 'Physician approval is required before this request can proceed.',
        detail = 'approval_required';
    end if;
    v_to := 'In Progress';
    v_outcome := 'executed';

  elsif p_decision = 'BLOCK' then
    if v_from = 'Awaiting Physician' and v_approval = 'pending' then
      raise exception using
        errcode = 'PT409', message = 'A physician approval is still pending for this task.',
        detail = 'approval_pending';
    end if;
    v_to := 'Declined';
    v_outcome := 'recorded';

  elsif p_hold_reason = 'needs_information' then
    v_to := 'On Hold';
    v_outcome := 'recorded';

  else
    -- HOLD for physician approval: create the approval, or reuse the one pending.
    if v_approval = 'pending' then
      v_request_id := v_task.approval_request_id;
      v_outcome := 'approval_reused';
    elsif v_approval = 'none' then
      perform 1
      from public.patient_assignments as assignment
      where assignment.patient_id = v_task.patient_id
      for update;

      perform 1
      from public.users as reviewer
      where reviewer.user_id in (
        select assignment.staff_user_id
        from public.patient_assignments as assignment
        where assignment.patient_id = v_task.patient_id
      )
      for share;

      perform 1
      from public.permissions as permission
      where permission.role = 'Physician'
        and permission.action = 'review_escalation'
      for share;

      for v_candidate_reviewer_id in
        select distinct reviewer.user_id
        from public.patient_assignments as assignment
        join public.users as reviewer
          on reviewer.user_id = assignment.staff_user_id
        join public.permissions as permission
          on permission.role = 'Physician'
         and permission.action = 'review_escalation'
         and permission.allowed is true
        where assignment.patient_id = v_task.patient_id
          and reviewer.role = 'Physician'
          and reviewer.is_active is true
      loop
        v_reviewer_count := v_reviewer_count + 1;
        v_reviewer_id := v_candidate_reviewer_id;
      end loop;

      if v_reviewer_count <> 1 then
        raise exception using
          errcode = 'PT409',
          message = 'No unique active assigned Physician is authorized to review this request.',
          detail = 'no_unique_reviewer';
      end if;

      -- request_details is structured and contains NO free text (no title,
      -- description or notes), so Admin/AI tooling never sees patient text here.
      insert into public.ai_requests (
        requested_by, patient_id, action, request_details, guardrail_decision, decision_reason
      ) values (
        p_actor_user_id,
        v_task.patient_id,
        'technician_task_approval',
        jsonb_build_object(
          'task_id', v_task.task_id,
          'category', v_task.category,
          'requested_action', 'physician_approval_for_task'
        )::text,
        'Escalate',
        'Human approval required'
      )
      returning request_id into v_new_request_id;

      insert into public.approvals (request_id, reviewer_id, status)
      values (v_new_request_id, v_reviewer_id, 'Pending');

      v_request_id := v_new_request_id;
      v_outcome := 'approval_requested';
    else
      raise exception using
        errcode = 'PT409',
        message = case v_approval
          when 'approved' then 'Physician approval has already been granted for this task.'
          when 'rejected' then 'The Physician rejected this task; it can only be declined.'
          else 'The linked approval is not valid for this task.'
        end,
        detail = 'approval_' || v_approval;
    end if;
    v_to := 'Awaiting Physician';
  end if;

  insert into public.technician_task_events (
    task_id, actor_user_id, actor_role, event_type, decision, hold_reason,
    from_status, to_status, guardrail_decision, guardrail_reason,
    internal_note, patient_message, approval_request_id
  ) values (
    v_task.task_id, p_actor_user_id, 'Technician', 'decision', p_decision, p_hold_reason,
    v_from, v_to, p_guardrail_decision, v_reason,
    v_note, v_message, v_request_id
  );

  update public.technician_tasks
  set status = v_to,
      latest_decision = p_decision,
      patient_message = coalesce(v_message, patient_message),
      approval_request_id = coalesce(v_request_id, approval_request_id),
      closed_at = case when v_to = 'Declined' then pg_catalog.now() else closed_at end
  where task_id = v_task.task_id;

  -- audit_logs never receives the note or patient text.
  insert into public.audit_logs (request_id, user_id, event_type, details)
  values (
    v_request_id,
    p_actor_user_id,
    'technician.task.decision.' || lower(p_decision),
    jsonb_build_object(
      'task_id', v_task.task_id, 'from', v_from, 'to', v_to,
      'hold_reason', p_hold_reason, 'guardrail_decision', p_guardrail_decision,
