-- Keeps tasks consistent with the shared assignment model.
--   INSERT: requested_by must be the Patient's own user; assigned_to must be an
--           active Technician assigned to that patient.
--   UPDATE: identity/intake fields are immutable; a changed assignee is re-validated.
create function hasf_private.technician_tasks_guard()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
begin
  if tg_op = 'UPDATE' then
    if new.task_id is distinct from old.task_id
       or new.patient_id is distinct from old.patient_id
       or new.requested_by is distinct from old.requested_by
       or new.category is distinct from old.category
       or new.requires_physician_approval is distinct from old.requires_physician_approval
       or new.created_at is distinct from old.created_at then
      raise exception using
        errcode = 'PT409',
        message = 'Immutable task fields cannot be changed.',
        detail = 'immutable_fields';
    end if;
    new.updated_at := pg_catalog.now();
  end if;

  if tg_op = 'INSERT' then
    if not exists (
      select 1
      from public.patients as patient
      where patient.patient_id = new.patient_id
        and patient.user_id = new.requested_by
    ) then
      raise exception using
        errcode = 'PT422',
        message = 'The requester is not the owner of this patient record.',
        detail = 'requester_mismatch';
    end if;
  end if;

  if tg_op = 'INSERT' or new.assigned_to is distinct from old.assigned_to then
    if not exists (
      select 1
      from public.users as technician
      join public.patient_assignments as assignment
        on assignment.staff_user_id = technician.user_id
       and assignment.patient_id = new.patient_id
      where technician.user_id = new.assigned_to
        and technician.role = 'Technician'
        and technician.is_active is true
    ) then
      raise exception using
        errcode = 'PT422',
        message = 'The assignee must be an active Technician assigned to this patient.',
        detail = 'assignee_not_eligible';
    end if;
  end if;

  return new;
end;
$function$;

