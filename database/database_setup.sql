as $function$
declare
  v_task public.technician_tasks;
begin
  if tg_op = 'INSERT' then
    select * into v_task from public.technician_tasks as t where t.task_id = new.task_id;
    if not found
       or v_task.category <> 'appointment_scheduling'
       or v_task.patient_id <> new.patient_id then
      raise exception using
        errcode = 'PT422', message = 'The appointment must belong to an appointment request of the same patient.',
        detail = 'task_mismatch';
    end if;
    if new.status <> 'Pending Confirmation' then
      raise exception using errcode = 'PT422', message = 'A new appointment must be pending.', detail = 'invalid_state';
    end if;
    if new.starts_at <= pg_catalog.now() then
      raise exception using errcode = 'PT422', message = 'The appointment must be in the future.', detail = 'invalid_date';
    end if;
    if not exists (
      select 1 from public.users as u
      where u.user_id = new.physician_user_id and u.role = 'Physician' and u.is_active is true
    ) then
      raise exception using errcode = 'PT422', message = 'The doctor is not an active Physician.', detail = 'physician_unavailable';
    end if;
    return new;
  end if;

  -- UPDATE: identity and slot are immutable; only status/confirmation may change.
  if new.appointment_id is distinct from old.appointment_id
     or new.task_id is distinct from old.task_id
     or new.patient_id is distinct from old.patient_id
     or new.physician_user_id is distinct from old.physician_user_id
     or new.starts_at is distinct from old.starts_at
     or new.ends_at is distinct from old.ends_at
     or new.physician_timezone is distinct from old.physician_timezone
     or new.reason is distinct from old.reason
     or new.created_at is distinct from old.created_at then
    raise exception using errcode = 'PT409', message = 'Immutable appointment fields cannot be changed.', detail = 'immutable_fields';
  end if;

  if new.status is distinct from old.status and not (
       (old.status = 'Pending Confirmation'
          and new.status in ('Needs Information', 'Awaiting Physician', 'Confirmed', 'Rejected', 'Cancelled'))
    or (old.status = 'Needs Information'
          and new.status in ('Pending Confirmation', 'Rejected', 'Cancelled'))
    or (old.status = 'Awaiting Physician'
          and new.status in ('Confirmed', 'Rejected'))
    or (old.status = 'Confirmed' and new.status = 'Completed')
  ) then
    raise exception using
      errcode = 'PT409', message = 'This appointment status change is not allowed.', detail = 'invalid_state';
  end if;

  new.updated_at := pg_catalog.now();
  return new;
end;
$function$;

