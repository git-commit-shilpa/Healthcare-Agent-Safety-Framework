-- p_from / p_to are LOCAL dates in the physician's time zone.
-- Confirmed/Completed appointments and 'unavailable' exceptions are subtracted.
-- p_ignore_appointment lets a confirmation re-check ignore the appointment itself.
create function hasf_private.generate_slots(
  p_physician_id integer,
  p_from date,
  p_to date,
  p_min_start timestamptz,
  p_ignore_appointment integer
)
returns table (slot_start timestamptz, slot_end timestamptz, slot_timezone text)
language sql
stable
security invoker
set search_path = pg_catalog
as $function$
  with tz as (
    select min(r.timezone) as name
    from public.physician_schedule_rules as r
    where r.physician_user_id = p_physician_id and r.is_active
  ),
  days as (
    select g::date as day
    from pg_catalog.generate_series(p_from::timestamp, p_to::timestamp, interval '1 day') as g
  ),
  rule_slots as (
    select (local_time at time zone r.timezone) as s,
           (local_time at time zone r.timezone) + pg_catalog.make_interval(mins => r.slot_minutes) as e,
           r.timezone as zone
    from public.physician_schedule_rules as r
    join days
      on extract(dow from days.day)::integer = r.weekday
     and days.day >= r.effective_from
     and (r.effective_to is null or days.day <= r.effective_to)
    cross join lateral pg_catalog.generate_series(
      r.start_minute::integer, (r.end_minute - r.slot_minutes)::integer, r.slot_minutes::integer
    ) as m(minute)
    cross join lateral (
      select days.day::timestamp + pg_catalog.make_interval(mins => m.minute) as local_time
    ) as lt
    where r.physician_user_id = p_physician_id
      and r.is_active
      -- Drop wall-clock times that do not exist (spring-forward gap).
      and ((local_time at time zone r.timezone) at time zone r.timezone) = local_time
  ),
  extra_slots as (
    select g as s,
           g + pg_catalog.make_interval(mins => x.slot_minutes) as e,
           (select tz.name from tz) as zone
    from public.physician_schedule_exceptions as x
    cross join lateral pg_catalog.generate_series(
      x.starts_at,
      x.ends_at - pg_catalog.make_interval(mins => x.slot_minutes),
      pg_catalog.make_interval(mins => x.slot_minutes)
    ) as g
    where x.physician_user_id = p_physician_id
      and x.kind = 'extra_availability'
      and x.is_active
  ),
  candidates as (
    select s, e, zone from rule_slots
    union
    select s, e, zone from extra_slots where zone is not null
  )
  select c.s, c.e, c.zone
  from candidates as c
  where hasf_private.physician_is_bookable(p_physician_id)
    and c.s >= p_min_start
    and (c.s at time zone c.zone)::date between p_from and p_to
    and not exists (
      select 1 from public.physician_schedule_exceptions as x
      where x.physician_user_id = p_physician_id and x.kind = 'unavailable' and x.is_active
        and pg_catalog.tstzrange(x.starts_at, x.ends_at) && pg_catalog.tstzrange(c.s, c.e)
    )
    and not exists (
      select 1 from public.appointments as a
      where a.physician_user_id = p_physician_id
        and a.status in ('Confirmed', 'Completed')
        and a.appointment_id is distinct from p_ignore_appointment
        and pg_catalog.tstzrange(a.starts_at, a.ends_at) && pg_catalog.tstzrange(c.s, c.e)
    )
  order by c.s;
$function$;

