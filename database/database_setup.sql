-- 5. Service requests (012)
create function public.submit_service_request(
  p_requested_by integer,
  p_category text,
  p_title text,
  p_description text,
  p_guardrail_reason text
)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
declare
  v_title text := btrim(p_title);
  v_description text := nullif(btrim(p_description), '');
  v_reason text := coalesce(nullif(btrim(p_guardrail_reason), ''), 'low_risk_permitted');
  v_patient_id integer;
  v_patient_count bigint;
  v_assignee integer;
  v_requires boolean;
  v_task_id integer;
  v_open_count integer;
begin
  if p_requested_by is null or p_requested_by <= 0
     or p_category is null
     or v_title is null or char_length(v_title) not between 1 and 200
     or (v_description is not null and char_length(v_description) > 1000)
     or char_length(v_reason) > 100 then
    raise exception using
      errcode = 'PT422', message = 'Invalid service request.', detail = 'invalid_input';
  end if;

  if p_category not in (
    'appointment_scheduling', 'test_result_upload', 'sample_collection',
    'supplies_equipment', 'documentation_request', 'general_inquiry',
    'medication_request', 'treatment_change_request', 'diagnosis_inquiry'
  ) then
    raise exception using
      errcode = 'PT422', message = 'Unknown request category.', detail = 'invalid_category';
  end if;

  v_requires := p_category in (
    'medication_request', 'treatment_change_request', 'diagnosis_inquiry'
  );

  perform 1 from public.users as requester where requester.user_id = p_requested_by for share;

  if not exists (
    select 1 from public.users as requester
    where requester.user_id = p_requested_by
      and requester.role = 'Patient'
      and requester.is_active is true
  ) then
    raise exception using
      errcode = 'PT403', message = 'The requester is not an active Patient account.',
      detail = 'not_patient';
  end if;

  perform 1 from public.permissions as permission
  where permission.role = 'Patient' and permission.action = 'submit_service_request'
  for share;

  if not exists (
    select 1 from public.permissions as permission
    where permission.role = 'Patient'
      and permission.action = 'submit_service_request'
      and permission.allowed is true
  ) then
    raise exception using
      errcode = 'PT403', message = 'The Patient account is not permitted to submit requests.',
      detail = 'permission_missing';
  end if;

  -- Serializes this Patient's submissions (same pattern as the correction RPC).
  perform 1 from public.patients as patient where patient.user_id = p_requested_by for update;

  select count(*) into v_patient_count
  from public.patients as patient where patient.user_id = p_requested_by;

  if v_patient_count <> 1 then
    raise exception using
      errcode = 'PT403', message = 'The Patient record link is missing or ambiguous.',
      detail = 'patient_link';
  end if;

  select patient.patient_id into v_patient_id
  from public.patients as patient where patient.user_id = p_requested_by;

  -- Abuse limit and duplicate prevention (open requests only).
  select count(*) into v_open_count
  from public.technician_tasks as task
  where task.patient_id = v_patient_id
    and task.status not in ('Completed', 'Declined', 'Cancelled');

  if v_open_count >= 10 then
    raise exception using
      errcode = 'PT429', message = 'Too many open service requests.', detail = 'too_many_open';
  end if;

  if exists (
    select 1 from public.technician_tasks as task
    where task.patient_id = v_patient_id
      and task.category = p_category
      and lower(btrim(task.title)) = lower(v_title)
      and task.status not in ('Completed', 'Declined', 'Cancelled')
  ) then
    raise exception using
      errcode = 'PT409', message = 'An identical request is already open.',
      detail = 'duplicate_request';
  end if;

  -- Deterministic, concurrency-safe assignment.
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('hasf.technician_task_assignment', 0)
  );

  perform 1 from public.permissions as permission
  where permission.role = 'Technician'
    and permission.action in ('view_assigned_task', 'update_task_status')
  for share;

  select candidate.user_id into v_assignee
  from public.patient_assignments as assignment
  join public.users as candidate
    on candidate.user_id = assignment.staff_user_id
  where assignment.patient_id = v_patient_id
    and candidate.role = 'Technician'
    and candidate.is_active is true
    and (
      select count(*) from public.permissions as permission
      where permission.role = 'Technician'
        and permission.action in ('view_assigned_task', 'update_task_status')
        and permission.allowed is true
    ) = 2
  order by
    (select count(*) from public.technician_tasks as open_task
      where open_task.assigned_to = candidate.user_id
        and open_task.status not in ('Completed', 'Declined', 'Cancelled')),
    candidate.user_id
  limit 1;

  if v_assignee is null then
    raise exception using
      errcode = 'PT422',
      message = 'No technician is currently available for your care team. Please contact your care team.',
      detail = 'no_eligible_technician';
  end if;

  insert into public.technician_tasks (
    patient_id, requested_by, assigned_to, category, title, description,
    status, requires_physician_approval
  ) values (
    v_patient_id, p_requested_by, v_assignee, p_category, v_title, v_description,
    'Submitted', v_requires
  )
  returning task_id into v_task_id;

  insert into public.technician_task_events (
    task_id, actor_user_id, actor_role, event_type, to_status,
    guardrail_decision, guardrail_reason
  ) values (
    v_task_id, p_requested_by, 'Patient', 'created', 'Submitted',
    case when v_requires then 'Escalate' else 'Allow' end, v_reason
  );

  insert into public.audit_logs (user_id, event_type, details)
  values (
    p_requested_by,
    'patient.service_request.submitted',
    jsonb_build_object('task_id', v_task_id, 'category', p_category)::text
  );

  -- The Patient is not told who was assigned.
  return jsonb_build_object(
    'task_id', v_task_id,
    'status', 'Submitted',
    'requires_physician_approval', v_requires
  );
end;
$function$;

create function public.cancel_service_request(
  p_task_id integer,
  p_requested_by integer
)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
declare
  v_task public.technician_tasks;
begin
  if p_task_id is null or p_task_id <= 0 or p_requested_by is null or p_requested_by <= 0 then
    raise exception using errcode = 'PT422', message = 'Invalid request.', detail = 'invalid_input';
  end if;

  perform 1 from public.users as requester where requester.user_id = p_requested_by for share;
  if not exists (
    select 1 from public.users as requester
    where requester.user_id = p_requested_by
      and requester.role = 'Patient' and requester.is_active is true
  ) then
    raise exception using errcode = 'PT403', message = 'The requester is not an active Patient account.', detail = 'not_patient';
  end if;

  select * into v_task
  from public.technician_tasks as task
  where task.task_id = p_task_id and task.requested_by = p_requested_by
  for update;

  if not found then
    raise exception using errcode = 'PT404', message = 'Request not found.', detail = 'not_found';
  end if;

  if v_task.status not in ('Submitted', 'In Review', 'On Hold') then
    raise exception using
      errcode = 'PT409', message = 'This request can no longer be cancelled.', detail = 'invalid_state';
  end if;

  update public.technician_tasks
  set status = 'Cancelled', closed_at = pg_catalog.now()
  where task_id = v_task.task_id;

  insert into public.technician_task_events (
    task_id, actor_user_id, actor_role, event_type, from_status, to_status
  ) values (v_task.task_id, p_requested_by, 'Patient', 'cancelled', v_task.status, 'Cancelled');

  insert into public.audit_logs (user_id, event_type, details)
  values (
    p_requested_by, 'patient.service_request.cancelled',
    jsonb_build_object('task_id', v_task.task_id, 'from', v_task.status)::text
  );

  return jsonb_build_object('task_id', v_task.task_id, 'status', 'Cancelled');
end;
$function$;

