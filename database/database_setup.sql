    'appointment_scheduling', 'test_result_upload', 'sample_collection',
    'supplies_equipment', 'documentation_request', 'general_inquiry',
    'medication_request', 'treatment_change_request', 'diagnosis_inquiry'
  )),
  constraint technician_tasks_title_check
    check (char_length(btrim(title)) between 1 and 200),
  constraint technician_tasks_description_check
    check (description is null or char_length(description) <= 1000),
  constraint technician_tasks_status_check check (status in (
    'Submitted', 'In Review', 'On Hold', 'Awaiting Physician',
    'In Progress', 'Completed', 'Declined', 'Cancelled'
  )),
  constraint technician_tasks_decision_check
    check (latest_decision is null or latest_decision in ('ALLOW', 'BLOCK', 'HOLD')),
  constraint technician_tasks_patient_message_check
    check (patient_message is null or char_length(patient_message) <= 500),
  -- Clinical categories always need a Physician; the flag cannot be false for them.
  constraint technician_tasks_clinical_flag_check check (
    category not in ('medication_request', 'treatment_change_request', 'diagnosis_inquiry')
    or requires_physician_approval is true
  ),
  constraint technician_tasks_closed_at_check check (
    (status in ('Completed', 'Declined', 'Cancelled')) = (closed_at is not null)
  ),
  constraint technician_tasks_awaiting_approval_check check (
    status <> 'Awaiting Physician' or approval_request_id is not null
  )
);

