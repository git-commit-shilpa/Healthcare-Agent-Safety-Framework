-- btree_gist supplies the GiST operator classes for integer / smallint equality that the EXCLUDE
-- constraints below need (the range overlap operator && on int4range / daterange / tstzrange is core).
-- On Supabase it is already installed in the "extensions" schema (v1.7), so this is a no-op there.
-- CREATE EXTENSION IF NOT EXISTS returns before any privilege check when the extension exists, and
-- PostgreSQL chooses the default GiST operator class by DATA TYPE, not by search_path, so the schema
-- the extension lives in does not matter (verified: identical result with it in "extensions"
-- and a session search_path that does not include that schema).
create extension if not exists btree_gist;

