-- ---------------------------------------------------------------------------
-- 2. correction_approval_status: 'not_requested' is now a valid state (no approval row yet).
--    Returns: none | not_requested | pending | approved | rejected | invalid
-- ---------------------------------------------------------------------------
create or replace function hasf_private.correction_approval_status(p_task public.technician_tasks)
returns text
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
declare
  v_count integer;
  v_status text;
  v_reviewer integer;
  v_reviewed_at timestamptz;
  v_patient integer;
  v_requester integer;
  v_action text;
begin
  if p_task.category is distinct from 'record_correction' or p_task.approval_request_id is null then
    return 'none';
  end if;

  perform 1 from public.approvals as a where a.request_id = p_task.approval_request_id for share;

  select r.patient_id, r.requested_by, r.action
  into v_patient, v_requester, v_action
  from public.ai_requests as r where r.request_id = p_task.approval_request_id;

  if not found
     or v_patient is distinct from p_task.patient_id
     or v_requester is distinct from p_task.requested_by
     or v_action is distinct from 'patient_treatment_correction' then
    return 'invalid';
  end if;

  select count(*) into v_count from public.approvals as a where a.request_id = p_task.approval_request_id;
  if v_count = 0 then
    return 'not_requested';
  elsif v_count <> 1 then
    return 'invalid';
  end if;

  select a.status, a.reviewer_id, a.reviewed_at
  into v_status, v_reviewer, v_reviewed_at
  from public.approvals as a where a.request_id = p_task.approval_request_id;

  if v_status = 'Pending' then
    return 'pending';
  elsif v_status in ('Approved', 'Rejected') then
    if v_reviewed_at is null or v_reviewer is null then
      return 'invalid';
    end if;
    if not exists (
      select 1
      from public.users as reviewer
      join public.patient_assignments as assignment
        on assignment.staff_user_id = reviewer.user_id
       and assignment.patient_id = p_task.patient_id
      join public.permissions as permission
        on permission.role = 'Physician'
       and permission.action = 'review_escalation'
       and permission.allowed is true
      where reviewer.user_id = v_reviewer
        and reviewer.role = 'Physician'
        and reviewer.is_active is true
    ) then
      return 'invalid';
    end if;
    return case when v_status = 'Approved' then 'approved' else 'rejected' end;
  end if;

  return 'invalid';
end;
$function$;

-- ---------------------------------------------------------------------------
-- 3. approvals INSERT guard (BEFORE INSERT only; UPDATE and DELETE are never touched).
--    For a correction that has a coordination task, an approval may be inserted ONLY by the Technician escalation,
--    and the trigger re-validates everything itself instead of trusting the transaction-local flag:
--      - the flag AND the acting user id were set by coordinate_correction_task in this transaction;
--      - that user is the task's assignee, an active Technician assigned to the patient with both task permissions;
--      - the task is a record_correction task for exactly this request, in status 'In Review';
--      - the request is a patient_treatment_correction of the same patient and requester, with no approval yet;
--      - the approval is Pending, not yet reviewed, for the UNIQUE assigned Physician who can process it.
--    Approvals of requests WITHOUT a coordination task (every historical correction, service-request approvals)
--    pass through unchanged.
-- ---------------------------------------------------------------------------
create function hasf_private.approvals_correction_guard()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog
as $function$
declare
  v_task public.technician_tasks;
  v_actor integer;
  v_candidate integer;
  v_reviewer integer;
  v_reviewer_count integer := 0;
begin
  select * into v_task
  from public.technician_tasks as t
  where t.approval_request_id = new.request_id and t.category = 'record_correction';

  if not found then
    return new;
  end if;

  begin
    v_actor := nullif(pg_catalog.current_setting('hasf.correction_actor', true), '')::integer;
  exception when others then
    v_actor := null;
  end;

  if pg_catalog.current_setting('hasf.correction_coordination', true) is distinct from 'on'
     or v_actor is null
     or v_actor is distinct from v_task.assigned_to
     or v_task.status <> 'In Review'
     or new.status is distinct from 'Pending'
     or new.reviewed_at is not null
     or new.reviewer_id is null
     or not exists (
       select 1
       from public.users as tech
       join public.patient_assignments as assignment
         on assignment.staff_user_id = tech.user_id and assignment.patient_id = v_task.patient_id
       where tech.user_id = v_actor and tech.role = 'Technician' and tech.is_active is true
         and (select count(*) from public.permissions as p
              where p.role = 'Technician' and p.action in ('view_assigned_task', 'update_task_status') and p.allowed is true) = 2
     )
     or not exists (
       select 1 from public.ai_requests as r
       where r.request_id = new.request_id and r.action = 'patient_treatment_correction'
         and r.patient_id = v_task.patient_id and r.requested_by = v_task.requested_by
     )
     or exists (select 1 from public.approvals as a where a.request_id = new.request_id) then
    raise exception using
      errcode = 'PT409',
      message = 'A correction approval can only be requested by the assigned Technician.',
      detail = 'approval_requires_technician_escalation';
  end if;

  for v_candidate in
    select distinct reviewer.user_id
    from public.patient_assignments as assignment
    join public.users as reviewer on reviewer.user_id = assignment.staff_user_id
    join public.permissions as permission
      on permission.role = 'Physician' and permission.action = 'review_escalation' and permission.allowed is true
    where assignment.patient_id = v_task.patient_id and reviewer.role = 'Physician' and reviewer.is_active is true
  loop
    v_reviewer_count := v_reviewer_count + 1;
    v_reviewer := v_candidate;
  end loop;

  if v_reviewer_count <> 1 or new.reviewer_id is distinct from v_reviewer then
    raise exception using
      errcode = 'PT409', message = 'No unique active assigned Physician is authorized to review this request.',
      detail = 'no_unique_reviewer';
  end if;
  if not hasf_private.physician_can_process_approvals(new.reviewer_id) then
    raise exception using
      errcode = 'PT409', message = 'The assigned Physician cannot process approvals yet.',
      detail = 'physician_unreachable';
  end if;

  return new;
end;
$function$;

